package com.example.nexusos.viewmodel

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.example.nexusos.data.InitialData
import com.example.nexusos.model.*
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

data class NexusUiState(
    val currentScreen: ScreenId = ScreenId.HOME,
    val backStack: List<ScreenId> = listOf(ScreenId.HOME),
    val themeAccent: ThemeAccent = ThemeAccent.EMERALD,
    val isPhoneFrame: Boolean = true,
    val apks: List<ApkProject> = InitialData.apks,
    val webs: List<WebProject> = InitialData.webs,
    val images: List<ImageItem> = InitialData.images,
    val videos: List<VideoItem> = InitialData.videos,
    val docs: List<DocumentItem> = InitialData.docs,
    val messages: List<ChatMessage> = InitialData.messages,
    val crashLogs: List<CrashLog> = InitialData.crashLogs,
    val isGenerating: Boolean = false,
    val statusNotification: String? = null
)

class NexusOsViewModel : ViewModel() {
    private val _uiState = MutableStateFlow(NexusUiState())
    val uiState: StateFlow<NexusUiState> = _uiState.asStateFlow()

    fun navigateTo(screen: ScreenId) {
        _uiState.update { state ->
            val newStack = state.backStack + screen
            state.copy(currentScreen = screen, backStack = newStack)
        }
    }

    fun navigateBack(): Boolean {
        val stack = _uiState.value.backStack
        if (stack.size > 1) {
            val newStack = stack.dropLast(1)
            _uiState.update { it.copy(currentScreen = newStack.last(), backStack = newStack) }
            return true
        } else if (_uiState.value.currentScreen != ScreenId.HOME) {
            _uiState.update { it.copy(currentScreen = ScreenId.HOME, backStack = listOf(ScreenId.HOME)) }
            return true
        }
        return false
    }

    fun setThemeAccent(accent: ThemeAccent) {
        _uiState.update { it.copy(themeAccent = accent) }
    }

    fun togglePhoneFrame() {
        _uiState.update { it.copy(isPhoneFrame = !it.isPhoneFrame) }
    }

    fun clearNotification() {
        _uiState.update { it.copy(statusNotification = null) }
    }

    fun addApk(apk: ApkProject) {
        _uiState.update { it.copy(apks = listOf(apk) + it.apks) }
    }

    fun generateApk(prompt: String, onFinished: (ApkProject) -> Unit = {}) {
        if (prompt.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(1500)
            val cleanName = prompt.trim().split(" ").firstOrNull()?.replaceFirstChar { it.uppercase() } ?: "NexusApp"
            val pkgSuffix = prompt.lowercase().filter { it.isLetter() }.take(8).ifEmpty { "app" }
            val newApk = ApkProject(
                id = "apk-${System.currentTimeMillis()}",
                appName = "$cleanName AI",
                packageName = "com.nexus.$pkgSuffix",
                version = "1.0.0",
                description = prompt,
                category = "AI Generated",
                kotlinCode = """
package com.nexus.$pkgSuffix

import android.os.Bundle
import androidx.appcompat.app.AppCompatActivity
import android.widget.TextView

class MainActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)
        // Generated by NexusOS 15 AI Studio for: $prompt
        val titleView = findViewById<TextView>(R.id.txtTitle)
        titleView.text = "$cleanName App Ready"
    }
}
                """.trimIndent(),
                xmlLayout = """
<?xml version="1.0" encoding="utf-8"?>
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:orientation="vertical"
    android:gravity="center"
    android:padding="24dp"
    android:background="#12141C">
    <TextView
        android:id="@+id/txtTitle"
        android:text="$prompt"
        android:textSize="20sp"
        android:textColor="#FFFFFF"
        android:layout_width="wrap_content"
        android:layout_height="wrap_content" />
</LinearLayout>
                """.trimIndent(),
                manifest = """
<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="com.nexus.$pkgSuffix">
    <application android:label="$cleanName AI">
        <activity android:name=".MainActivity" android:exported="true"/>
    </application>
</manifest>
                """.trimIndent(),
                buildStatus = "compiled"
            )
            _uiState.update { it.copy(apks = listOf(newApk) + it.apks, isGenerating = false, statusNotification = "APK $cleanName Compiled (Scheme v2/v3 Signed)") }
            onFinished(newApk)
        }
    }

    fun analyzeCustomCrash(rawLog: String, onFinished: (CrashLog) -> Unit = {}) {
        if (rawLog.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(1200)
            val excType = when {
                rawLog.contains("Archive is not a ZIP archive") -> "java.io.IOException"
                rawLog.contains("NullPointerException") -> "java.lang.NullPointerException"
                rawLog.contains("ClassNotFoundException") -> "java.lang.ClassNotFoundException"
                else -> "java.lang.Exception"
            }
            val excMsg = when {
                rawLog.contains("Archive is not a ZIP archive") -> "Archive is not a ZIP archive"
                rawLog.contains("NullPointerException") -> "Attempt to read from null object reference"
                rawLog.contains("ClassNotFoundException") -> "Class not found in DexClassLoader"
                else -> "Uncaught runtime exception"
            }

            val newLog = CrashLog(
                id = "crash-${System.currentTimeMillis()}",
                ver = "2.26.8",
                permission = "APP",
                abi = "arm64-v8a",
                model = if (rawLog.contains("MODEL:")) rawLog.substringAfter("MODEL:").substringBefore("\n").trim() else "moto g54 5G",
                sdk = "35",
                release = "15",
                targetSdk = "30",
                exceptionType = excType,
                exceptionMessage = excMsg,
                stackTrace = rawLog
            )
            _uiState.update { it.copy(crashLogs = listOf(newLog) + it.crashLogs, isGenerating = false) }
            onFinished(newLog)
        }
    }


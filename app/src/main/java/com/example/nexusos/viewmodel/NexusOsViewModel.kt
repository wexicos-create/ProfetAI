    fun generateWeb(prompt: String, onFinished: (WebProject) -> Unit = {}) {
        if (prompt.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(1500)
            val title = prompt.take(20).trim() + "..."
            val newWeb = WebProject(
                id = "web-${System.currentTimeMillis()}",
                title = title,
                prompt = prompt,
                htmlCode = """
<div style="font-family: sans-serif; text-align: center; padding: 2rem;">
  <h2>$prompt</h2>
  <p>Generated by NexusOS 15 WebForge Engine.</p>
  <button style="padding: 10px 20px; background: #3B82F6; color: white; border-radius: 8px;">Explore</button>
</div>
                """.trimIndent(),
                cssCode = "body { background: #0b0f17; color: #fff; margin: 0; }",
                jsCode = "console.log('WebForge app ready.');"
            )
            _uiState.update { it.copy(webs = listOf(newWeb) + it.webs, isGenerating = false, statusNotification = "Web project generated!") }
            onFinished(newWeb)
        }
    }

    fun generateImage(prompt: String, style: String, aspect: String) {
        if (prompt.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(2000)
            val seed = (1..999).random()
            val newImg = ImageItem(
                id = "img-${System.currentTimeMillis()}",
                title = prompt.take(24) + "...",
                prompt = prompt,
                url = "https://picsum.photos/seed/$seed/800/600",
                style = style,
                aspectRatio = aspect
            )
            _uiState.update { it.copy(images = listOf(newImg) + it.images, isGenerating = false, statusNotification = "Image synthesized with Imagen 3") }
        }
    }

    fun generateVideo(prompt: String, res: String, aspect: String) {
        if (prompt.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(2500)
            val newVid = VideoItem(
                id = "vid-${System.currentTimeMillis()}",
                title = prompt.take(22) + "...",
                prompt = prompt,
                duration = "0:07",
                resolution = res,
                thumbnailUrl = "https://picsum.photos/seed/veovideo/800/450"
            )
            _uiState.update { it.copy(videos = listOf(newVid) + it.videos, isGenerating = false, statusNotification = "Cinematic video rendered via Veo 3.1") }
        }
    }

    fun updateDoc(doc: DocumentItem) {
        _uiState.update { state ->
            val updated = state.docs.map { if (it.id == doc.id) doc else it }
            state.copy(docs = updated, statusNotification = "File '${doc.name}' saved")
        }
    }

    fun aiRefactorDoc(docId: String, prompt: String, onFinished: (DocumentItem) -> Unit = {}) {
        if (prompt.isBlank()) return
        _uiState.update { it.copy(isGenerating = true) }
        viewModelScope.launch {
            delay(1200)
            val currentDoc = _uiState.value.docs.find { it.id == docId }
            if (currentDoc != null) {
                val newContent = "${currentDoc.content}\n\n<!-- AI Refactor: $prompt -->\n- [x] Processed by Gemini OS Assistant on ${System.currentTimeMillis()}"
                val updated = currentDoc.copy(content = newContent, updatedAt = System.currentTimeMillis())
                _uiState.update { state ->
                    state.copy(
                        docs = state.docs.map { if (it.id == docId) updated else it },
                        isGenerating = false,
                        statusNotification = "Document refactored by AI"
                    )
                }
                onFinished(updated)
            }
        }
    }

    fun sendChatMessage(text: String) {
        if (text.isBlank()) return
        val userMsg = ChatMessage(
            id = "msg-${System.currentTimeMillis()}",
            sender = "user",
            text = text
        )
        _uiState.update { it.copy(messages = it.messages + userMsg, isGenerating = true) }

        viewModelScope.launch {
            delay(1200)
            val lower = text.lowercase()
            val (reply, actionCard) = when {
                lower.contains("crash") || lower.contains("stack") || lower.contains("zip") || lower.contains("archive") || lower.contains("exception") -> {
                    Pair(
                        "I analyzed the crash report (\"java.io.IOException: Archive is not a ZIP archive\"). The issue occurs because the target APK file lacks valid ZIP magic bytes (PK\\x03\\x04). You can view the full diagnostic report and run 1-click repair in the Crash Inspector!",
                        ActionCard("apk", "Open Crash Inspector", ScreenId.CRASH_ANALYZER)
                    )
                }
                lower.contains("apk") || lower.contains("android") || lower.contains("app") -> {
                    Pair(
                        "I generated Android APK project source code for \"$text\". You can compile, test, and export it in APK Studio!",
                        ActionCard("apk", "Open APK Studio", ScreenId.APK_STUDIO)
                    )
                }
                lower.contains("web") || lower.contains("site") || lower.contains("page") || lower.contains("html") -> {
                    Pair(
                        "I built the website layout for \"$text\". You can preview it live in WebForge AI!",
                        ActionCard("web", "Open WebForge", ScreenId.WEB_FORGE)
                    )
                }
                lower.contains("image") || lower.contains("photo") || lower.contains("draw") -> {
                    Pair(
                        "I've prepared the prompt for your AI image generation in Nexus Canvas.",
                        ActionCard("image", "Open Image Studio", ScreenId.IMAGE_STUDIO)
                    )
                }
                lower.contains("video") || lower.contains("film") -> {
                    Pair(
                        "Ready to render your cinematic video in CineGen AI.",
                        ActionCard("video", "Open Video Suite", ScreenId.VIDEO_SUITE)
                    )
                }
                else -> {
                    Pair(
                        "NexusOS 15 AI Assistant is fully operational with Gemini 3.6 Flash. What would you like to build?",
                        null
                    )
                }
            }

            val botMsg = ChatMessage(
                id = "msg-${System.currentTimeMillis() + 1}",
                sender = "gemini",
                text = reply,
                actionCard = actionCard
            )
            _uiState.update { it.copy(messages = it.messages + botMsg, isGenerating = false) }
        }
    }
}
